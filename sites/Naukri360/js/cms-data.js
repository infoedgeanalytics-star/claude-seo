function buildBreadcrumbs(slug, title, pages) {
  // Standard prefix: Home (naukri.com root) → Naukri360 (campaign root) → page chain.
  var root = "https://www.naukri.com";
  var base = root + "/naukri360";
  var crumbs = [
    {n:"Home", u:root},
    {n:"Naukri360", u:base}
  ];
  var parts = String(slug||"").split("/").filter(Boolean);
  var path = "";
  for (var i = 0; i < parts.length; i++) {
    path = path ? path + "/" + parts[i] : parts[i];
    var isLast = (i === parts.length - 1);
    var name;
    if (isLast) {
      name = title;
    } else if (pages && pages[path] && pages[path].title) {
      name = pages[path].title;
    } else {
      name = parts[i].replace(/-/g," ").replace(/\b\w/g,function(c){return c.toUpperCase()});
    }
    crumbs.push({n:name, u:base + "/" + path});
  }
  return crumbs;
}
